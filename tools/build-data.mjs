#!/usr/bin/env node
// Writes data/data.js — all card/deck JSON as one classic script, so the game
// also works when index.html is opened directly (file://), where fetch() is blocked.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f, fb) => { const p = path.join(root, 'data', f); return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : fb; };

export function buildDataJs() {
  const data = {
    cards: rd('cards.json', []), imported: rd('imported.json', []),
    effects: rd('effects.json', {}), decks: rd('decks.json', []),
  };
  fs.writeFileSync(path.join(root, 'data', 'data.js'),
    '// GENERATED by tools/build-data.mjs from data/*.json — do not edit by hand.\nwindow.RM_DATA = ' + JSON.stringify(data) + ';\n');
  console.log('wrote data/data.js');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) buildDataJs();
